"""Reticulum set-up for the two RNS modes, plus the reconnect-aware announcer.

* ``standalone``: the bridge writes the RNS config itself (own instance, not a transport node,
  one TCPClientInterface) and starts its own Reticulum. RNS reconnects a TCPClientInterface on its own.
* ``shared``: attach to the shared instance of another process (``require_shared_instance``).
"""
from __future__ import annotations

import logging
import os
import threading
import time

from .config import RnsConfig, rns_config_value

log = logging.getLogger("kestrel.rns")

INTERFACE_NAME = "MeshChatX"
FOLLOW_UPS = (10.0, 60.0)
SHARED_RNS_CONFIG = """[reticulum]
  enable_transport = No
  share_instance = Yes
  instance_name = default

[interfaces]
"""


def render_standalone_config(rns: RnsConfig, passphrase: str | None = None) -> str:
    """The complete RNS config file for ``standalone`` mode (pure function)."""
    lines = [
        "# Generated by kestrel-bridge at every start from [rns] in bridge.toml. Do not edit.",
        "[reticulum]",
        "  enable_transport = No",
        "  share_instance = No",
        "  panic_on_interface_error = No",
        "",
        "[interfaces]",
        f"  [[{INTERFACE_NAME}]]",
        "    type = TCPClientInterface",
        "    enabled = Yes",
        f"    target_host = {rns.tcp_host}",
        f"    target_port = {rns.tcp_port}",
    ]
    if rns.ifac_name:
        lines.append(f"    network_name = {rns_config_value('rns.ifac_name', rns.ifac_name)}")
    if passphrase:
        lines.append(f"    passphrase = {rns_config_value('rns.ifac_passphrase_file content', passphrase)}")
    return "\n".join(lines) + "\n"


def prepare_rns_config(rns: RnsConfig) -> str:
    """Write the RNS config file into ``rns.config_dir`` and return its path.

    standalone: always (re)generated, mode 0600 (it may contain the IFAC passphrase).
    shared: only created when missing, as a minimal config without interfaces.
    """
    os.makedirs(rns.config_dir, exist_ok=True)
    path = os.path.join(rns.config_dir, "config")
    if rns.mode == "standalone":
        text = render_standalone_config(rns, rns.read_ifac_passphrase())
    elif os.path.exists(path):
        return path
    else:
        text = SHARED_RNS_CONFIG
    tmp = path + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)
    return path


def start_reticulum(rns: RnsConfig):
    """Start Reticulum for the configured mode and return the RNS.Reticulum instance."""
    import RNS
    prepare_rns_config(rns)
    if rns.mode == "standalone":
        return RNS.Reticulum(configdir=rns.config_dir, loglevel=rns.log_level, require_shared_instance=False)
    ret = RNS.Reticulum(configdir=rns.config_dir, loglevel=rns.log_level, require_shared_instance=True)
    if not ret.is_connected_to_shared_instance:
        raise SystemError("not connected to a shared instance")
    return ret


def tcp_client_interfaces() -> list:
    """The TCPClientInterface objects of the running Reticulum instance (standalone mode)."""
    import RNS
    return [i for i in RNS.Transport.interfaces if type(i).__name__ == "TCPClientInterface"]


def interfaces_online(interfaces) -> bool:
    return any(bool(getattr(i, "online", False)) for i in interfaces)


class AnnounceWatcher:
    """Announce on start, periodically, and after every interface (re)connect.

    The first announce right after a (re)connect can be lost (the remote transport node may not be
    reading from the new connection yet) and a phone could then not find S until the next periodic
    announce, so every start/reconnect is followed by short follow-up announces
    (``follow_ups`` = seconds after the connect; default 10 s and 60 s).

    ``interfaces()`` returns the interface objects to watch, or None when there is nothing to watch
    (shared mode: periodic announces only). An interface counts as connected while its ``online``
    flag is set. A new connection is recognised by an offline period or by a new socket object
    (a reconnect that is faster than the poll interval).
    """

    def __init__(self, announce, interfaces=None, interval: float = 1800.0, poll: float = 1.0,
                 clock=time.monotonic, follow_ups=FOLLOW_UPS):
        self.announce = announce
        self.interfaces = interfaces or (lambda: None)
        self.interval = interval
        self.poll = poll
        self._clock = clock
        self.follow_ups = tuple(follow_ups)
        self._pending: list[float] = []   # due times of follow-up announces
        self._sig = None          # connection signature seen at the last tick
        self._last = None         # time of the last announce
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None

    @staticmethod
    def _signature(ifaces):
        if ifaces is None:
            return ("untracked",)
        return tuple(sorted(id(getattr(i, "socket", None)) for i in ifaces if getattr(i, "online", False)))

    def tick(self) -> bool:
        """One poll step; returns True when an announce was sent."""
        ifaces = self.interfaces()
        sig = self._signature(ifaces)
        online = ifaces is None or interfaces_online(ifaces)
        now = self._clock()
        reason = None
        if not online:
            self._pending = []
        else:
            if sig != self._sig:
                reason = "startup" if self._last is None else "interface reconnected"
                self._pending = [now + d for d in self.follow_ups]
            elif self._pending and now >= self._pending[0]:
                reason = "follow-up"
                while self._pending and now >= self._pending[0]:
                    self._pending.pop(0)
            elif self._last is None or now - self._last >= self.interval:
                reason = "periodic"
        self._sig = sig
        if reason is None:
            return False
        try:
            self.announce()
        except Exception:
            log.exception("announce failed")
            return False
        self._last = now
        log.info("announced kestrel.bridge (%s)", reason)
        return True

    def start(self) -> None:
        self._thread = threading.Thread(target=self._run, name="kestrel-announce", daemon=True)
        self._thread.start()

    def stop(self) -> None:
        self._stop.set()

    def _run(self) -> None:
        while not self._stop.is_set():
            try:
                self.tick()
            except Exception:
                log.exception("announce watcher error")
            self._stop.wait(self.poll)
